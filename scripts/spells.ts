/**
 * addon/SecondWind/Spells_Classic.lua and Spells_Forever.lua: every rank of
 * the tools' spells (Tools.lua's SPELLS: an English name, a kind, the ids it
 * lists), by the first id the entry lists: a cast is matched to its tool by
 * its id, never by its name. A rank is a spell of the same English name a
 * class or a people learns (the client's SkillLineAbility), each game's, from
 * wow-data's databases (../wow-data, its pinned builds); the ids the entry
 * lists always among them.
 *
 *   bun scripts/spells.ts           write them
 *   bun scripts/spells.ts --check   fail if one isn't up to date
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { openDb } from "../../wow-data/src/db";

const ROOT = join(import.meta.dir, "..");
const ADDON = join(ROOT, "addon", "SecondWind");
type Game = "classic" | "forever";

// Tools.lua's SPELLS: { "Name", "kind", id, id... }
export function toolSpells(): { name: string; ids: number[] }[] {
  const src = readFileSync(join(ADDON, "Tools.lua"), "utf8");
  const block = src.slice(src.indexOf("local SPELLS = {"), src.indexOf("\n}\n", src.indexOf("local SPELLS = {")));
  const out: { name: string; ids: number[] }[] = [];
  for (const m of block.matchAll(/\{\s*"((?:[^"\\]|\\.)*)",\s*"[a-z]+",\s*([\d,\s]+)\}/g))
    out.push({ name: m[1], ids: m[2].split(",").map((s) => Number(s.trim())).filter((n) => n > 0) });
  if (!out.length) throw new Error("Tools.lua: no SPELLS found");
  return out;
}

function lua(game: Game): string {
  const db = openDb(game);
  const ranks = db.query(
    `SELECT s.ID AS id FROM client_SpellName s
     WHERE s.Name_lang = ? AND s.ID IN (SELECT Spell FROM client_SkillLineAbility) ORDER BY s.ID`,
  );
  const lines = [
    "-- Generated by scripts/spells.ts from wow-data's database: don't edit.",
    "-- Every rank of the tools' spells (Tools.lua's SPELLS), by the first id an entry lists.",
    "local _, ns = ...",
    "",
    "ns.toolRanks = {",
  ];
  for (const t of toolSpells()) {
    const ids = new Set<number>(t.ids);
    for (const r of ranks.all(t.name) as { id: number }[]) ids.add(r.id);
    lines.push(`  [${t.ids[0]}] = { ${[...ids].sort((a, b) => a - b).join(", ")} },`);
  }
  lines.push("}", "");
  db.close();
  return lines.join("\n");
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  let stale = false;
  for (const [game, file] of [
    ["classic", "Spells_Classic.lua"],
    ["forever", "Spells_Forever.lua"],
  ] as const) {
    const out = join(ADDON, file);
    const text = lua(game);
    if (check) {
      if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
        console.error(`✗ addon/SecondWind/${file} is out of date: run bun scripts/spells.ts`);
        stale = true;
      }
    } else {
      writeFileSync(out, text);
      console.log(`✓ addon/SecondWind/${file}`);
    }
  }
  if (stale) process.exit(1);
}
