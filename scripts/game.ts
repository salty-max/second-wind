/**
 * addon/SecondWind/Game_Classic.lua and Game_Forever.lua, each game's own
 * tables from wow-data's databases (../wow-data, its pinned builds):
 * - every rank of the tools' spells (Tools.lua's SPELLS: an English name, a
 *   kind, the ids it lists), by the first id the entry lists: a cast is
 *   matched to its tool by its id, never by its name. A rank is a spell of the
 *   same English name a class or a people learns (the client's
 *   SkillLineAbility); the ids the entry lists always among them.
 * - every area's English name by id: a debrief of before 15 October 2026,
 *   kept by its places' English names, finds their ids on a client of any
 *   language (the game names an area only in the client's).
 * - creature-type names in every language, to recover ids in older saved
 *   reports after a client-language change. Only unambiguous names are kept.
 *
 *   bun scripts/game.ts           write them
 *   bun scripts/game.ts --check   fail if one isn't up to date
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type * as WowDb from "../../wow-data/src/db";
import { familyPath } from "./root";

// through the family folder, from a worktree too (scripts/root.ts)
const { openDb } = (await import(familyPath("wow-data", "src", "db.ts"))) as typeof WowDb;

const ROOT = join(import.meta.dir, "..");
const ADDON = join(ROOT, "addon", "SecondWind");
type Game = "classic" | "forever";

// Tools.lua's SPELLS: { "Name", "kind", id, id... }
export function toolSpells(): { name: string; ids: number[] }[] {
  const src = readFileSync(join(ADDON, "Tools.lua"), "utf8");
  const block = src.slice(src.indexOf("local SPELLS = {"), src.indexOf("\n}\n", src.indexOf("local SPELLS = {")));
  const out: { name: string; ids: number[] }[] = [];
  for (const m of block.matchAll(/\{\s*"((?:[^"\\]|\\.)*)",\s*"[a-z]+",\s*([\d,\s]+)\}/g))
    out.push({ name: m[1], ids: m[2].split(",").map((s) => Number(s.trim())).filter((n) => n > 0) });
  if (!out.length) throw new Error("Tools.lua: no SPELLS found");
  return out;
}

function lua(game: Game): string {
  const db = openDb(game);
  const ranks = db.query(
    `SELECT s.ID AS id FROM client_SpellName s
     WHERE s.Name_lang = ? AND s.ID IN (SELECT Spell FROM client_SkillLineAbility) ORDER BY s.ID`,
  );
  const lines = [
    "-- Generated by scripts/game.ts from wow-data's database: don't edit.",
    "-- Every rank of the tools' spells (Tools.lua's SPELLS), by the first id an entry lists;",
    "-- every area's English name by id (an older debrief's places).",
    "local _, ns = ...",
    "",
    "ns.toolRanks = {",
  ];
  for (const t of toolSpells()) {
    const ids = new Set<number>(t.ids);
    for (const r of ranks.all(t.name) as { id: number }[]) ids.add(r.id);
    lines.push(`  [${t.ids[0]}] = { ${[...ids].sort((a, b) => a - b).join(", ")} },`);
  }
  lines.push("}", "", "ns.areaEnglish = {");
  const areas = db.query("SELECT ID AS id, AreaName_lang AS name FROM client_AreaTable WHERE AreaName_lang <> '' ORDER BY ID").all() as { id: number; name: string }[];
  for (let i = 0; i < areas.length; i += 6) lines.push(`  ${areas.slice(i, i + 6).map((a) => `[${a.id}]=${JSON.stringify(a.name.trim())},`).join(" ")}`);
  lines.push("}", "", "ns.legacyTypeIds = {");
  const types = db.query("SELECT name, id FROM name WHERE kind = 'creature_type' ORDER BY name, id").all() as { name: string; id: number }[];
  const byName = new Map<string, Set<number>>();
  for (const { name, id } of types) {
    if (!name.trim()) continue;
    const ids = byName.get(name) ?? new Set<number>();
    ids.add(id);
    byName.set(name, ids);
  }
  for (const [name, ids] of byName)
    if (ids.size === 1) lines.push(`  [${JSON.stringify(name)}] = ${[...ids][0]},`);
  lines.push("}", "");
  db.close();
  return lines.join("\n");
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  let stale = false;
  for (const [game, file] of [
    ["classic", "Game_Classic.lua"],
    ["forever", "Game_Forever.lua"],
  ] as const) {
    const out = join(ADDON, file);
    const text = lua(game);
    if (check) {
      if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
        console.error(`✗ addon/SecondWind/${file} is out of date: run bun scripts/game.ts`);
        stale = true;
      }
    } else {
      writeFileSync(out, text);
      console.log(`✓ addon/SecondWind/${file}`);
    }
  }
  if (stale) process.exit(1);
}
