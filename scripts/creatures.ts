/**
 * addon/SecondWind/Creatures_Classic.lua and Creatures_Forever.lua: each
 * creature's portrait (its display id, for
 * SetPortraitTextureFromCreatureDisplayID) by its id; their names are each
 * language's (scripts/creature_names.ts). From wow-data's databases
 * (../wow-data, its pinned sources: Questie's world, the Classic database for
 * what it lacks), each game's own: every creature with a model that can be a
 * foe (not a critter, a totem, a pet or one of the databases' helpers).
 * Forever's own creatures have no model there: Page.lua finds theirs in the
 * game by a hidden model.
 *
 *   bun scripts/creatures.ts           write them
 *   bun scripts/creatures.ts --check   fail if one isn't up to date
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { openDb } from "../../wow-data/src/db";

const ROOT = join(import.meta.dir, "..");
const ADDON = join(ROOT, "addon", "SecondWind");
type Game = "classic" | "forever";

// critters, totems, non-combat pets, gas clouds
const NOT_FOES = new Set([8, 11, 12, 13]);
// the databases' helpers: triggers, dummies, markers, unused entries
const HELPER = /\b(Trigger|Doodad|Dummy|Marker|Bunny|DND|UNUSED|unused|Visual|Generator|TEST|Test)\b|^\[/;

export type Foe = { id: number; name: string; model: number };
// A game's foes, by id (model 0: none known).
export function foes(game: Game): Foe[] {
  const db = openDb(game);
  const rows = db
    .query(
      `SELECT c.id, n.name, c.display_ids, c.type_id FROM creature c
       JOIN name n ON n.kind = 'creature' AND n.id = c.id AND n.locale = 'enUS'
       WHERE c.removed IS NOT 1
       ORDER BY c.id`,
    )
    .all() as { id: number; name: string; display_ids: string | null; type_id: number | null }[];
  db.close();
  return rows
    .filter((r) => !(r.type_id != null && NOT_FOES.has(r.type_id)) && !HELPER.test(r.name))
    .map((r) => ({ id: r.id, name: r.name, model: Number((r.display_ids ?? "").split(",")[0]) || 0 }));
}

const chunks = (items: string[], n: number) => {
  const out: string[] = [];
  for (let i = 0; i < items.length; i += n) out.push("    " + items.slice(i, i + n).join(", ") + ",");
  return out.join("\n");
};

function lua(game: Game): string {
  const list = foes(game);
  const lines = [
    "-- Generated by scripts/creatures.ts from wow-data's database: don't edit.",
    "-- Each creature's portrait, its display id, by its id.",
    "local _, ns = ...",
    "",
    "ns.creatures = {",
    "  -- creature id = display id",
    "  models = {",
    chunks(
      list.filter((c) => c.model > 0).map((c) => `[${c.id}]=${c.model}`),
      10,
    ),
    "  },",
  ];
  lines.push("}", "");
  return lines.join("\n");
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  let stale = false;
  for (const [game, file] of [
    ["classic", "Creatures_Classic.lua"],
    ["forever", "Creatures_Forever.lua"],
  ] as const) {
    const out = join(ADDON, file);
    const text = lua(game);
    if (check) {
      if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
        console.error(`✗ addon/SecondWind/${file} is out of date: run bun run creatures`);
        stale = true;
      }
    } else {
      writeFileSync(out, text);
      console.log(`✓ addon/SecondWind/${file}`);
    }
  }
  if (stale) process.exit(1);
}
