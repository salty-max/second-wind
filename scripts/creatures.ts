/**
 * addon/SecondWind/Creatures.lua: each creature's portrait, as the Field
 * Journal draws it (its display id, for SetPortraitTextureFromCreatureDisplayID),
 * by its id and by its name (a foe Forever's damage meter names only). From
 * the Field Journal's data/creatures.json: the creatures of the original world
 * (the CMaNGOS Classic database, pinned there; Forever's new ones are found
 * in the game by a hidden model, Page.lua).
 *
 *   bun scripts/creatures.ts [path to the Field Journal's data/creatures.json]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..");
const SOURCE = process.argv[2] ?? join(ROOT, "..", "field-journal", "data", "creatures.json");
const OUT = join(ROOT, "addon", "SecondWind", "Creatures.lua");

type Creature = { id: number; name: string; model: number };
const creatures: Creature[] = JSON.parse(readFileSync(SOURCE, "utf8"));
const withModel = creatures.filter((c) => c.model > 0).sort((a, b) => a.id - b.id);
// A name's creature: the first of the name with a portrait.
const byName = new Map<string, number>();
for (const c of withModel) if (!byName.has(c.name)) byName.set(c.name, c.id);

const q = (s: string) => JSON.stringify(s);
const chunks = (items: string[], n: number) => {
  const out: string[] = [];
  for (let i = 0; i < items.length; i += n) out.push("    " + items.slice(i, i + n).join(", ") + ",");
  return out.join("\n");
};
const lua = `-- Generated by scripts/creatures.ts from the Field Journal's creatures (the
-- CMaNGOS Classic database): don't edit. Each creature's portrait, its
-- display id, by its id and by its name.
local _, ns = ...

ns.creatures = {
  -- creature id = display id
  models = {
${chunks(withModel.map((c) => `[${c.id}]=${c.model}`), 10)}
  },
  -- a name = its creature id
  names = {
${chunks([...byName].map(([name, id]) => `[${q(name)}]=${id}`), 4)}
  },
}
`;
writeFileSync(OUT, lua);
console.log(`✓ ${OUT.slice(ROOT.length + 1)}: ${withModel.length} creatures, ${byName.size} names`);
